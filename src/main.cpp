	Snake::s_maxScore = getSavedMaxScore();

	SetConfigFlags(FLAG_WINDOW_RESIZABLE);
	InitWindow(DEFAULT_SCREEN_SIZE, DEFAULT_SCREEN_SIZE, "Snake");

	auto icon = LoadImage("resources/icon.png");
