int constexpr GRID_SIZE = 21;
float constexpr TILE_SIZE = 40.f;
float constexpr FREE_SPACE = 50.f;
float constexpr DEFAULT_SCREEN_SIZE = GRID_SIZE * TILE_SIZE + FREE_SPACE * 2;
float constexpr DEFAULT_MONITOR_HEIGHT = 1080.f;

char constexpr SAVE_FILE[] = "save.dat";
int8_t constexpr SAVE_DATA_XOR_KEY = 47;

int getSavedMaxScore();
void saveMaxScore(int maxScore);

using Grid = std::array<std::array<Rectangle, GRID_SIZE>, GRID_SIZE>;

using Direction = enum { Up, Down, Left, Right, };
inline std::string constexpr directionToString(Direction direction) {
	switch (direction) {
		case Up:    return "up";
		case Down:  return "down";
		case Left:  return "left";
		case Right: return "right";
	}
	return "";
}

using Tile = std::array<int, 2>;

struct Snake {
	using Tiles = std::deque<Tile>;
	Tiles tiles;

	Tile getNextTile() const;
	void step(Grid& grid);

	Direction direction;
	
	using Apple = Tile;
	std::vector<Apple> apples;

	int score;
	static int s_maxScore;
};

int Snake::s_maxScore = 0;

void draw(Grid const& grid, Snake const& snake, bool hasLost);

static inline Rectangle       constexpr& rectFromIndices(Tile const& indices, Grid&       grid) { return grid[indices[0]][indices[1]]; }
static inline Rectangle const constexpr& rectFromIndices(Tile const& indices, Grid const& grid) { return grid[indices[0]][indices[1]]; }

static std::random_device rd;
static std::mt19937 e{rd()};
static std::uniform_int_distribution<int> dist{0, GRID_SIZE - 1};
	
